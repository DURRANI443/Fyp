import { expect, test } from '@playwright/test';
import type { Page } from '@playwright/test';

async function login(page: Page, role = 'Customer') {
  await page.goto('/', { waitUntil: 'domcontentloaded' });
  await page.getByRole('button', { name: new RegExp(`^${role} `) }).click();
  await page.getByRole('button', { name: 'Enter workspace' }).click();
  await expect(page.getByRole('navigation', { name: 'Main navigation' })).toBeVisible();
}

test('customer can ask a grounded question and hand off to a staff member', async ({ page, browser }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await login(page);
  await expect(page.getByRole('heading', { name: 'The essentials' })).toBeVisible();
  await expect(page.locator('.product-card')).toHaveCount(6);
  await page.screenshot({ path: testInfo.outputPath('customer-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: 'Get support', exact: true }).click();
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('What is your return policy?');
  await page.getByRole('button', { name: 'Send message' }).click();
  await expect(page.locator('.message-bubble').filter({ hasText: '30 days' })).toBeVisible();
  await expect(page.locator('.citations')).toContainText('Returns and eligibility');
  await expect(page.getByText('Local support workflow', { exact: true }).last()).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('grounded-chat-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: 'Talk to a person' }).click();
  await expect(page.getByText(/automatic replies are paused/)).toBeVisible();
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('Please explain what happens after the return request.');
  await page.getByRole('button', { name: 'Send message' }).click();
  await expect(page.locator('.message-bubble').filter({ hasText: 'Please explain what happens' })).toBeVisible();
  const staffContext = await browser.newContext({ baseURL: 'http://127.0.0.1:8001', viewport: { width: 1440, height: 1000 } });
  const staffPage = await staffContext.newPage();
  await login(staffPage, 'Support');
  await staffPage.locator('.ticket-card').filter({ hasText: 'What is your return policy?' }).click();
  await staffPage.getByRole('button', { name: 'Assign to me' }).click();
  await expect(staffPage.getByLabel('Reply to Alex Morgan')).toBeVisible();
  await staffPage.getByLabel('Reply to Alex Morgan').fill('Our returns team reviews the request and shares the next steps. No refund is issued automatically.');
  await staffPage.getByRole('button', { name: 'Send reply' }).click();
  await expect(page.getByText('Our returns team reviews the request and shares the next steps. No refund is issued automatically.', { exact: true })).toBeVisible({ timeout: 15000 });
  await staffPage.screenshot({ path: testInfo.outputPath('staff-inbox-desktop.png'), fullPage: true });
  await staffPage.getByRole('button', { name: 'Resolve conversation', exact: true }).click();
  await staffPage.getByLabel('Resolution summary').fill('Explained the review process and confirmed that return requests do not issue refunds.');
  await staffPage.getByRole('button', { name: 'Mark as resolved' }).click();
  await expect(page.locator('.message-bubble').filter({ hasText: 'The assistant is available again' })).toBeVisible({ timeout: 15000 });
  await expect(page.getByRole('button', { name: 'Talk to a person' })).toBeVisible();
  expect(errors).toEqual([]);
  await staffContext.close();
});

test('orders require confirmation and a return appears in the staff review queue', async ({ page, browser }) => {
  await login(page);
  await page.getByRole('button', { name: 'My orders', exact: true }).click();
  await page.locator('.order-list-card').filter({ hasText: 'NS-1042' }).click();
  await page.getByRole('button', { name: 'Cancel order', exact: true }).click();
  await page.getByRole('button', { name: 'Review request' }).click();
  await expect(page.getByRole('dialog')).toContainText('Confirm cancellation');
  await page.getByRole('button', { name: 'Go back', exact: true }).click();
  await expect(page.locator('.order-detail .panel-heading')).toContainText('Processing');
  await page.getByRole('button', { name: 'Cancel order', exact: true }).click();
  await page.getByRole('button', { name: 'Review request' }).click();
  await page.getByRole('button', { name: 'Confirm cancellation', exact: true }).click();
  await expect(page.locator('.success-box')).toContainText('Your cancellation was confirmed.');
  await expect(page.locator('.order-detail .panel-heading')).toContainText('Cancelled');
  await expect(page.getByRole('button', { name: 'Cancel order', exact: true })).toHaveCount(0);
  await page.locator('.order-list-card').filter({ hasText: 'NS-1024' }).click();
  await page.getByRole('button', { name: 'Start a return', exact: true }).click();
  await page.getByLabel('Reason for return').fill('The linen shirt does not fit.');
  await page.getByRole('button', { name: 'Review request' }).click();
  await page.getByRole('button', { name: 'Submit return request', exact: true }).click();
  await expect(page.locator('.success-box')).toContainText('Your return request was submitted for review.');
  await expect(page.locator('.return-list')).toContainText('Requested');
  const staffContext = await browser.newContext({ baseURL: 'http://127.0.0.1:8001', viewport: { width: 1440, height: 1000 } });
  const staffPage = await staffContext.newPage();
  await login(staffPage, 'Support');
  await staffPage.getByLabel('Filter team').selectOption('returns');
  await staffPage.locator('.ticket-card').filter({ hasText: /NS-1024|return request/i }).first().click();
  await staffPage.getByRole('button', { name: 'Assign to me' }).click();
  await staffPage.getByRole('button', { name: 'Approve', exact: true }).click();
  await expect(staffPage.locator('.return-review')).toContainText('Approved');
  await page.reload();
  await page.getByRole('button', { name: 'My orders', exact: true }).click();
  await page.locator('.order-list-card').filter({ hasText: 'NS-1024' }).click();
  await expect(page.locator('.return-list')).toContainText('Approved');
  await staffContext.close();
});

test('admin can approve knowledge, update routing availability and inspect activity', async ({ page }, testInfo) => {
  await login(page, 'Admin');
  await page.getByRole('button', { name: 'Knowledge library', exact: true }).click();
  await page.getByRole('button', { name: 'Add knowledge', exact: true }).click();
  await page.getByLabel('Source key').fill('browser-test-care');
  await page.getByLabel('Title', { exact: true }).fill('Browser test care guide');
  await page.getByLabel('Source content').fill('For this synthetic store demonstration, wash the test cotton item on a cool cycle and air dry.');
  await page.getByRole('button', { name: 'Save draft', exact: true }).click();
  const card = page.locator('.knowledge-card').filter({ hasText: 'Browser test care guide' });
  await expect(card).toContainText('Draft');
  await card.getByRole('button', { name: 'Approve source', exact: true }).click();
  await expect(card).toContainText('Approved');
  await page.screenshot({ path: testInfo.outputPath('admin-knowledge-desktop.png'), fullPage: true });
  await page.getByRole('button', { name: 'Team & routing', exact: true }).click();
  const member = page.locator('.team-card').filter({ hasText: 'Sam Taylor' });
  await member.getByRole('checkbox', { name: 'Available for support' }).uncheck();
  await member.getByRole('button', { name: 'Save changes' }).click();
  await expect(member.getByRole('status')).toContainText('Changes saved');
  await page.reload();
  await page.getByRole('button', { name: 'Team & routing', exact: true }).click();
  await expect(member.getByRole('checkbox', { name: 'Available for support' })).not.toBeChecked();
  await member.getByRole('checkbox', { name: 'Available for support' }).check();
  await member.getByRole('button', { name: 'Save changes' }).click();
  await page.getByRole('button', { name: 'Activity & insights', exact: true }).click();
  await expect(page.locator('.audit-table')).toContainText('Knowledge.Approval Changed');
  await expect(page.locator('.metric-grid')).toContainText('Conversations');
});

test('mobile customer can navigate, inspect order eligibility and use support without overflow', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await login(page);
  await page.screenshot({ path: testInfo.outputPath('customer-mobile.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'My orders', exact: true }).click();
  await page.locator('.order-list-card').filter({ hasText: 'NS-1001' }).click();
  await expect(page.locator('.order-detail')).toContainText('NS-1001');
  await expect(page.getByRole('button', { name: 'Start a return', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Get support', exact: true }).click();
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('What is your shipping policy?');
  await page.getByRole('button', { name: 'Send message' }).click();
  await expect(page.locator('.citations')).toContainText('Shipping and tracking');
  await page.screenshot({ path: testInfo.outputPath('support-mobile.png'), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
});
